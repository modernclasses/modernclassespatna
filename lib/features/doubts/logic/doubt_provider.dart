import 'package:flutter/material.dart';
import '../data/models/doubt_model.dart';
import '../data/repositories/doubt_repository.dart';

class DoubtProvider extends ChangeNotifier {
  final DoubtRepository _repository;

  List<DoubtModel> _doubts = [];
  String _selectedFilter =
      'All'; // 'All', 'My Doubts', 'Resolved', 'Unresolved'
  bool _isLoading = false;
  String? _errorMessage;

  List<DoubtModel> get doubts => _doubts;
  String get selectedFilter => _selectedFilter;
  bool get isLoading => _isLoading;
  String? get errorMessage => _errorMessage;

  DoubtProvider({DoubtRepository? repository})
    : _repository = repository ?? DoubtRepositoryImpl() {
    fetchDoubts();
  }

  Future<void> fetchDoubts() async {
    _isLoading = true;
    _errorMessage = null;
    notifyListeners();

    try {
      final fetched = await _repository.getDoubts();
      _doubts = fetched;
    } catch (e) {
      _errorMessage = e.toString();
    } finally {
      _isLoading = false;
      notifyListeners();
    }
  }

  List<DoubtModel> getFilteredDoubts(String currentUserId) {
    switch (_selectedFilter) {
      case 'Resolved':
        return _doubts
            .where((d) => d.studentId == currentUserId && d.isResolved)
            .toList();
      case 'Unresolved':
        return _doubts
            .where((d) => d.studentId == currentUserId && !d.isResolved)
            .toList();
      default:
        return _doubts.where((d) => d.studentId == currentUserId).toList();
    }
  }

  void setFilter(String filter) {
    _selectedFilter = filter;
    notifyListeners();
  }

  Future<void> askNewDoubt({
    required String studentId,
    required String batchId,
    required String studentName,
    required String subject,
    required String questionText,
    String? attachmentUrl,
  }) async {
    _isLoading = true;
    _errorMessage = null;
    notifyListeners();

    try {
      final newDoubt = DoubtModel(
        id: '', // Will be generated by Postgres UUID
        studentId: studentId,
        batchId: batchId,
        studentName: studentName,
        subject: subject,
        questionText: questionText,
        attachmentUrl: attachmentUrl,
        createdAt: DateTime.now(),
        isResolved: false,
      );

      final createdDoubt = await _repository.postDoubt(newDoubt);
      _doubts.insert(0, createdDoubt);
    } catch (e) {
      _errorMessage = e.toString();
    } finally {
      _isLoading = false;
      notifyListeners();
    }
  }

  Future<void> resolveDoubt({
    required String doubtId,
    required String facultyReply,
    required String facultyName,
    required String resolvedBy,
  }) async {
    _isLoading = true;
    _errorMessage = null;
    notifyListeners();

    try {
      // 1. Await the database update first
      final updatedDoubt = await _repository.resolveDoubt(
        doubtId,
        facultyReply,
        facultyName,
        resolvedBy,
      );

      final index = _doubts.indexWhere((d) => d.id == doubtId);
      if (index != -1) {
        _doubts[index] = updatedDoubt;
      }
    } catch (e) {
      _errorMessage = e.toString();
    } finally {
      _isLoading = false;
      notifyListeners();
    }
  }
}
